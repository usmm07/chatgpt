const supportedLanguages = Object.keys(translations);

function resolveTranslation(lang, key) {
  return key.split('.').reduce((value, part) => (value ? value[part] : undefined), translations[lang]);
}

function getTranslation(lang, key) {
  const direct = resolveTranslation(lang, key);
  if (direct !== undefined) return direct;
  if (lang !== 'en') {
    const fallback = resolveTranslation('en', key);
    if (fallback !== undefined) return fallback;
  }
  return '';
}

function detectPreferredLanguage() {
  const saved = localStorage.getItem('diio-lang');
  if (saved && supportedLanguages.includes(saved)) {
    return saved;
  }

  const candidates = navigator.languages || [navigator.language];
  const match = candidates
    .map((value) => (value ? value.slice(0, 2).toLowerCase() : ''))
    .find((code) => supportedLanguages.includes(code));

  return match || 'en';
}

let currentLang = detectPreferredLanguage();

function updateTexts(lang) {
  const textNodes = document.querySelectorAll('[data-i18n]');
  const placeholders = document.querySelectorAll('[data-i18n-placeholder]');

  textNodes.forEach((node) => {
    const translation = getTranslation(lang, node.dataset.i18n);
    if (translation) {
      node.textContent = translation;
    }
  });

  placeholders.forEach((node) => {
    const translation = getTranslation(lang, node.dataset.i18nPlaceholder);
    if (translation) {
      node.setAttribute('placeholder', translation);
    }
  });

  document.documentElement.lang = lang;
  currentLang = lang;
  localStorage.setItem('diio-lang', lang);

  document.querySelectorAll('.lang-btn').forEach((button) => {
    button.classList.toggle('active', button.dataset.lang === lang);
  });
}

async function handleSubmit(event) {
  event.preventDefault();
  const form = event.target;
  const statusNode = document.getElementById('form-status');
  statusNode.textContent = '';

  const payload = {
    name: form.name.value.trim(),
    email: form.email.value.trim(),
    phone: form.phone.value.trim(),
    message: form.message.value.trim(),
  };

  if (!payload.name) {
    statusNode.textContent = getTranslation(currentLang, 'contact.form.validation.name');
    statusNode.style.color = '#ef4444';
    return;
  }

  if (!payload.email || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(payload.email)) {
    statusNode.textContent = getTranslation(currentLang, 'contact.form.validation.email');
    statusNode.style.color = '#ef4444';
    return;
  }

  try {
    const response = await fetch('/api/contact', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload),
    });

    if (!response.ok) {
      throw new Error('Request failed');
    }

    form.reset();
    statusNode.textContent = getTranslation(currentLang, 'contact.form.success');
    statusNode.style.color = 'var(--accent-2)';
  } catch (error) {
    statusNode.textContent = getTranslation(currentLang, 'contact.form.error');
    statusNode.style.color = '#ef4444';
  }
}

window.addEventListener('DOMContentLoaded', () => {
  updateTexts(currentLang);

  document.querySelectorAll('.lang-btn').forEach((button) => {
    button.addEventListener('click', () => updateTexts(button.dataset.lang));
  });

  const form = document.getElementById('contact-form');
  form.addEventListener('submit', handleSubmit);
});
